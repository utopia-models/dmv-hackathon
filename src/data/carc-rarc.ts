// Overrule — patient-facing CARC/RARC denial-code table.
// Meanings paraphrased from the public X12 Claim Adjustment Reason Code / Remittance Advice
// Remark Code lists; plainEnglish + nextAction are written for PATIENTS, authored at the
// DMV Hackathon 2026-07-25. Deterministic lookup — no AI involved in anything in this file.

import type { DenialCode, CarcGroup } from "@/lib/overrule-types";

export const GROUP_LABELS: Record<CarcGroup, string> = {
  CO: "Contractual Obligation",
  PR: "Patient Responsibility",
  OA: "Other Adjustment",
  PI: "Payer Initiated Reduction",
};

function carc(
  code: string,
  group: CarcGroup,
  meaning: string,
  category: string,
  plainEnglish: string,
  appealable: DenialCode["appealable"],
  nextAction: string
): DenialCode {
  return { code, type: "CARC", group, meaning, category, plainEnglish, appealable, nextAction };
}

function rarc(
  code: string,
  meaning: string,
  category: string,
  plainEnglish: string,
  appealable: DenialCode["appealable"],
  nextAction: string
): DenialCode {
  return { code, type: "RARC", meaning, category, plainEnglish, appealable, nextAction };
}

