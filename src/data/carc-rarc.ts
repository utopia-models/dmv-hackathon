const INDEX = new Map<string, DenialCode>();
for (const e of [...CARC_ENTRIES, ...RARC_ENTRIES]) {
  // CARC indexed with and without group prefix: "45", "CO-45", "PR-45"
  if (e.type === "CARC") {
    INDEX.set(`${e.group}-${e.code}`, e);
    if (!INDEX.has(e.code)) INDEX.set(e.code, e);
  } else {
    INDEX.set(e.code, e);
  }
}

/** Lookup by raw token: "CO-45", "CO45", "45" (CARC), "N115", "MA130" (RARC). */
export function lookupDenialCode(raw: string): DenialCode | undefined {
  const t = raw.trim().toUpperCase().replace(/\s+/g, "");
  const norm = t.replace(/^(CO|PR|OA|PI)(\d)/, "$1-$2");
  return INDEX.get(norm) ?? INDEX.get(norm.replace(/^(?:CO|PR|OA|PI)-/, ""));
}

